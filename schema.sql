create table if not exists public.students (
  id bigint generated by default as identity primary key,
  student_id text not null unique,
  first_name text not null,
  last_name text not null,
  program text not null,
  year_level integer not null check (year_level between 1 and 4),
  email text not null,
  created_at timestamptz not null default now()
);

alter table public.students enable row level security;

-- This policy is suitable only for a trusted, private demo. For a public
-- deployment, replace it with authenticated-user policies before launch.
create policy "Allow public student management"
on public.students for all
to anon, authenticated
using (true)
with check (true);
